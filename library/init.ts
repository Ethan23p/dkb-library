// init — the initialize capability (CONTRACTS D4, D5).
//
// Creates exactly three artifacts in the target dir — config.yml, kb.sqlite,
// convention.md — and runs the D5 init transaction sequence: tx 1 asserts
// kb/schema-version on entity 0; tx 2 asserts a placeholder entity; tx 3
// retracts it. Post-init: valid schema, zero current sources, the placeholder
// dance visible in the log.

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { DkbError, ExitCode } from "./errors";
import { KB_FILENAME, Ledger, SCHEMA_VERSION } from "./ledger";

export interface EngineDef {
  /** Engine title, e.g. "Epistack". */
  title: string;
  /** The convention.md seed text — owned by the engine, not the library. */
  conventionSeed: string;
}

const PLACEHOLDER = { e: 1, a: "kb/placeholder", v: "init-probe" } as const;

/** Initialize a KB in `dir`. Writes only within `dir` (D11). */
export function initKb(dir: string, engine: EngineDef): { dir: string; kbPath: string } {
  const kbPath = path.join(dir, KB_FILENAME);
  for (const artifact of ["config.yml", KB_FILENAME, "convention.md"]) {
    if (existsSync(path.join(dir, artifact))) {
      throw new DkbError(
        ExitCode.STATE,
        `'${artifact}' already exists in ${dir} — refusing to overwrite`,
        "init is non-destructive; pass --dir <path> pointing at an empty directory",
      );
    }
  }
  mkdirSync(dir, { recursive: true });

  // kb.sqlite — schema + the D5 init transaction sequence.
  const ledger = Ledger.create(kbPath);
  try {
    ledger.transact([{ e: 0, a: "kb/schema-version", v: SCHEMA_VERSION, added: 1 }]);
    ledger.transact([{ ...PLACEHOLDER, added: 1 }]);
    ledger.transact([{ ...PLACEHOLDER, added: 0 }]);
  } finally {
    ledger.close();
  }

  // config.yml — engine config: title, paths, versions (D4). LF line endings.
  const configYml = [
    `# ${engine.title} — engine configuration (generated by init)`,
    `title: ${engine.title}`,
    "paths:",
    `  kb: ${KB_FILENAME}`,
    "  convention: convention.md",
    "versions:",
    `  dkb-library: ${SCHEMA_VERSION}`,
    `  kb-schema: ${SCHEMA_VERSION}`,
    "",
  ].join("\n");
  writeFileSync(path.join(dir, "config.yml"), configYml);

  // convention.md — seed text supplied by the engine.
  writeFileSync(path.join(dir, "convention.md"), engine.conventionSeed);

  return { dir, kbPath };
}
